// Regenerate web/face-mean.mjs: MediaPipe's canonical face (the average face
// its landmarker is built around), as 2-D points in the page's face space —
// eye centres at (-0.5, 0) and (0.5, 0), y down. Selfie mode's caricature is
// "push a person's measurements away from this".
//
//   curl -o canonical.obj https://raw.githubusercontent.com/google-ai-edge/mediapipe/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
//   node scripts/build-face-mean.mjs canonical.obj
//
// The model is Apache-2.0 (google-ai-edge/mediapipe).
import { readFileSync, writeFileSync } from "node:fs";
import { alignFace } from "../web/face.mjs";

const obj = readFileSync(process.argv[2] || "canonical.obj", "utf8");
// The .obj is y-up; the page, like an image, is y-down.
const pts = obj.split("\n").filter(l => l.startsWith("v ")).map(l => l.split(/\s+/).slice(1, 3).map(Number))
  .map(([x, y]) => [x, -y]);
if (pts.length !== 468) throw new Error(`expected 468 vertices, got ${pts.length}`);
const { pts: aligned } = alignFace(pts);
if (!(aligned[10][1] < 0 && aligned[152][1] > 0)) throw new Error("canonical face came out upside down");
const flat = aligned.flatMap(p => p.map(v => +v.toFixed(3)));
writeFileSync(new URL("../web/face-mean.mjs", import.meta.url),
  `// GENERATED by scripts/build-face-mean.mjs from MediaPipe's canonical_face_model.obj
// (Apache-2.0, google-ai-edge/mediapipe) — do not edit by hand.
// 468 points, x,y interleaved, in face space (eye centres at x = -0.5 and 0.5).
export const MEAN_FACE = [${flat.join(",")}];
`);
console.log("wrote web/face-mean.mjs", flat.length / 2, "points");
